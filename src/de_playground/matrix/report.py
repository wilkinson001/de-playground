"""Render probe results as `docs/engine-format-matrix.md`."""

from __future__ import annotations

from datetime import date

from de_playground.matrix.probes import ENGINES, FORMATS, OPS, ProbeResult

_TITLES = {"ducklake": "DuckLake", "iceberg": "Iceberg", "delta": "Delta Lake"}
_CELLS = {"ok": "✅", "fail": "❌", "n/a": "—"}

_HEADER = """# Engine × format capability matrix

Generated by `make matrix` on {date} against the running stack — every cell is an operation that
was actually attempted, not taken from documentation. ✅ works · ❌ fails · — not applicable.

Operations, on a 2-column table in namespace `matrix`:
- **create** — create a new table · **append** — insert rows
- **overwrite** — replace all rows the engine's idiomatic way (Spark `INSERT OVERWRITE`, delta-rs/PyIceberg
  overwrite mode, DuckDB delete + insert in one transaction, ClickHouse `TRUNCATE` + insert)
- **merge** — upsert (`MERGE INTO`, or the library's merge/upsert API)
- **read** — count a seed table written by another engine (DuckDB seeds DuckLake; Spark seeds Iceberg and Delta)
"""


def render_markdown(results: list[ProbeResult], run_date: date) -> str:
    by_key = {(r.engine, r.format, r.op): r for r in results}
    parts = [_HEADER.format(date=run_date.isoformat())]
    for fmt in FORMATS:
        engines = [e for e in ENGINES if any(r.engine == e and r.format == fmt for r in results)]
        if not engines:
            continue
        lines = [f"## {_TITLES[fmt]}", "", "| Engine | " + " | ".join(OPS) + " |", "|---" * (len(OPS) + 1) + "|"]
        for engine in engines:
            cells = [_CELLS[by_key[(engine, fmt, op)].status] if (engine, fmt, op) in by_key else " " for op in OPS]
            lines.append(f"| {engine} | " + " | ".join(cells) + " |")
        parts.append("\n".join(lines) + "\n")

    notes = [r for r in results if r.status == "fail"]
    na = {(r.engine, r.format): r.detail for r in results if r.status == "n/a"}
    parts.append("## Notes\n")
    parts.append("\n".join(f"- **{r.engine} / {r.format} / {r.op}**: {r.detail}" for r in notes) or "No failures.")
    caveats = [r for r in results if r.status == "ok" and r.detail]
    if caveats:
        parts.append("\n\nCaveats:\n\n" + "\n".join(f"- {r.engine} / {r.format} / {r.op}: {r.detail}" for r in caveats))
    if na:
        parts.append("\n\nNot applicable:\n\n" + "\n".join(f"- {e} / {f}: {d}" for (e, f), d in na.items()))
    return "\n".join(parts) + "\n"
