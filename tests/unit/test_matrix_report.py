from datetime import date

from de_playground.matrix.probes import OPS, ProbeResult
from de_playground.matrix.report import render_markdown


def test_render_markdown():
    results = [
        *[ProbeResult("duckdb", "ducklake", op, "ok", "") for op in OPS],
        *[ProbeResult("spark", "ducklake", op, "n/a", "no connector") for op in OPS],
        ProbeResult("clickhouse", "delta", "create", "ok", ""),
        ProbeResult("clickhouse", "delta", "append", "fail", "Code: 48. Not implemented"),
    ]
    md = render_markdown(results, date(2026, 11, 11))

    assert md.startswith("# Engine × format capability matrix\n")
    assert "Generated by `make matrix` on 2026-11-11" in md
    assert (
        "## DuckLake\n\n"
        "| Engine | create | append | overwrite | merge | read |\n"
        "|---|---|---|---|---|---|\n"
        "| duckdb | ✅ | ✅ | ✅ | ✅ | ✅ |\n"
        "| spark | — | — | — | — | — |\n"
    ) in md
    assert "| clickhouse | ✅ | ❌ |   |   |   |\n" in md  # unprobed cells stay blank
    assert "## Iceberg" not in md  # formats with no results are omitted
    assert "- **clickhouse / delta / append**: Code: 48. Not implemented" in md
    assert "**spark / ducklake" not in md  # n/a reasons are not listed as failures
    assert "- spark / ducklake: no connector" in md


def test_ok_results_with_a_caveat_are_listed():
    results = [ProbeResult("clickhouse", "iceberg", "append", "ok", "on a table created by Spark")]
    md = render_markdown(results, date(2026, 11, 11))
    assert "| clickhouse |   | ✅ |" in md
    assert "Caveats:\n\n- clickhouse / iceberg / append: on a table created by Spark" in md
